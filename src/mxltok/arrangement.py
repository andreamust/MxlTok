"""Interleaving of the token sequences of the parts of a score.

``part_first`` writes each part in turn::

    part:start part:instrument:Violin measure ... measure ... part:end
    part:start part:instrument:Cello  measure ... measure ... part:end

``measure_first`` writes each measure in turn, with every part inside it::

    measure part:start part:instrument:Violin ... part:end
            part:start part:instrument:Cello  ... part:end
    measure ...
"""

from __future__ import annotations

from collections.abc import Sequence

from mxltok.config import Arrangement
from mxltok.vocabulary import INSTRUMENT_PREFIX, MEASURE, PART_END, PART_START

# A part as its instrument category (if known) and its tokens.
PartTokens = tuple[str | None, list[str]]


# --------------------------------------------------------------------------- #
# Encoding
# --------------------------------------------------------------------------- #


def join_parts(
    parts: Sequence[tuple[str, list[str]]], arrangement: Arrangement
) -> list[str]:
    """Interleave the tokens of each ``(instrument, tokens)`` part."""
    if arrangement == "part_first":
        return [
            token
            for instrument, tokens in parts
            for token in (
                PART_START,
                f"{INSTRUMENT_PREFIX}{instrument}",
                *tokens,
                PART_END,
            )
        ]
    measures = [split_measures(tokens) for _, tokens in parts]
    joined: list[str] = []
    for index in range(max((len(m) for m in measures), default=0)):
        joined.append(MEASURE)
        for (instrument, _), part_measures in zip(parts, measures, strict=True):
            joined += [PART_START, f"{INSTRUMENT_PREFIX}{instrument}"]
            if index < len(part_measures):
                joined += part_measures[index]
            joined.append(PART_END)
    return joined


def split_measures(tokens: Sequence[str]) -> list[list[str]]:
    """Return the tokens between consecutive ``measure`` tokens.

    Tokens before the first ``measure`` (such as a ``repeat:forward``) form a
    measure of their own; an empty last measure is dropped.
    """
    measures: list[list[str]] = []
    current: list[str] = []
    for token in tokens:
        if token == MEASURE:
            if current or measures:
                measures.append(current)
            current = []
        else:
            current.append(token)
    if current:
        measures.append(current)
    return measures


# --------------------------------------------------------------------------- #
# Decoding
# --------------------------------------------------------------------------- #


def split_parts(tokens: Sequence[str], arrangement: Arrangement) -> list[PartTokens]:
    """Separate the parts of a sequence: the inverse of :func:`join_parts`.

    Each part's tokens are returned in the part-first form, with their
    ``measure`` tokens. Sequences generated by a model need not be well
    formed: missing ``part:start``/``part:end`` and ``measure`` tokens are
    tolerated.
    """
    if arrangement == "part_first":
        return _split_part_first(tokens)
    return _split_measure_first(tokens)


def _split_part_first(tokens: Sequence[str]) -> list[PartTokens]:
    parts: list[PartTokens] = []
    current: list[str] = []
    instrument: str | None = None
    for token in tokens:
        if token in (PART_START, PART_END):
            if token == PART_END and current:
                parts.append((instrument, current))
            current, instrument = [], None
        elif token.startswith(INSTRUMENT_PREFIX):
            instrument = token.removeprefix(INSTRUMENT_PREFIX)
        else:
            current.append(token)
    if current:
        parts.append((instrument, current))
    return parts


def _split_measure_first(tokens: Sequence[str]) -> list[PartTokens]:
    groups = _measure_groups(tokens)
    if not groups:
        return []
    num_parts = max(len(blocks) for blocks in groups)
    instruments: list[str | None] = [None] * num_parts
    for blocks in groups:
        for index, (instrument, _) in enumerate(blocks):
            if instruments[index] is None:
                instruments[index] = instrument

    # A model often writes the key, time and tempo of a measure in its first
    # part only: the first measure of every other part inherits them.
    parts: list[list[str]] = [[] for _ in range(num_parts)]
    signatures: list[str] = []
    for blocks in groups:
        signatures = next(
            (found for _, block in blocks if (found := _signature_tokens(block))),
            signatures,
        )
        for index, (_, block) in enumerate(blocks):
            if not block:
                continue  # an empty block would become an empty measure
            if not parts[index]:
                block = _missing_signatures(signatures, block) + block
            parts[index] += [MEASURE, *block]
    return list(zip(instruments, parts, strict=True))


def _measure_groups(tokens: Sequence[str]) -> list[list[PartTokens]]:
    """Return, for each measure, the ``(instrument, tokens)`` of its parts.

    Tokens outside ``part:start``/``part:end`` blocks are ignored, as are
    ``measure`` tokens with no part after them.
    """
    groups: list[list[PartTokens]] = []
    blocks: list[PartTokens] = []
    block: list[str] | None = None
    instrument: str | None = None
    for token in tokens:
        if token in (MEASURE, PART_START, PART_END) and block is not None:
            blocks.append((instrument, block))
            block = None
        if token == MEASURE:
            if blocks:
                groups.append(blocks)
            blocks = []
        elif token == PART_START:
            block, instrument = [], None
        elif token.startswith(INSTRUMENT_PREFIX):
            if block is not None and instrument is None:
                instrument = token.removeprefix(INSTRUMENT_PREFIX)
        elif token != PART_END and block is not None:
            block.append(token)
    if block is not None:
        blocks.append((instrument, block))
    if blocks:
        groups.append(blocks)
    return groups


def _signature_tokens(tokens: Sequence[str]) -> list[str]:
    return [token for token in tokens if token.startswith(("key:", "time:", "tempo:"))]


def _missing_signatures(signatures: Sequence[str], block: Sequence[str]) -> list[str]:
    """Return the signature tokens of ``signatures`` that ``block`` lacks."""
    present = {token.rsplit(":", 1)[0] for token in _signature_tokens(block)}
    return [token for token in signatures if token.rsplit(":", 1)[0] not in present]
